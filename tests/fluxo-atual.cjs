const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
const {chromium} = require(process.env.VIHVA_PLAYWRIGHT || 'playwright');
const raiz = pathToFileURL(path.resolve(__dirname, '..') + path.sep).href;
(async () => {
  const navegador = await chromium.launch({channel: process.env.VIHVA_BROWSER || undefined});
  try {
    const p = await navegador.newPage({viewport:{width:1440,height:900}});
    const erros = [], rede = [];
    p.on('pageerror', e => erros.push(e.message));
    p.on('request', r => { if (/^https?:/.test(r.url())) rede.push(r.url()); });
    const abrir = rota => p.goto(raiz + rota);
    const link = name => p.getByRole('link', {name,exact:true});
    const botao = name => p.getByRole('button', {name,exact:true});
    await abrir('index.html');
    assert.equal(await p.getByRole('heading', {name:'Cuidar começa por aqui.'}).count(),1);
    assert.equal(await p.locator('form').count(),0);
    await link('Começar').click();
    await p.waitForURL('**/painel.html');
    await p.evaluate(legado => {
      legado.limpezaInicialNovembro = true;
      legado.atendimentos.find(a => a.id_atendimento === 3).status = 'EM_ANDAMENTO';
      delete legado.consultas[0].medicamentos;
      legado.medicamentos = [{id_medicamento:1,nome_medicamento:'Registro legado'}];
      legado.consultas_medicamentos = [{id_consulta:1,id_medicamento:1,posologia:null}];
      localStorage.setItem(VihvaConfig.chave, JSON.stringify(legado));
    }, require('./cenario-fixture.cjs')());
    await p.reload();
    assert.equal(await p.locator('main .page-head .btn-receber-paciente').count(),1);
    assert.equal(await p.locator('nav a[href="medicamentos.html"], nav a[href="usuarios.html"], nav a[href="novo-atendimento.html"]').count(),0);
    assert.equal(await p.getByRole('columnheader',{name:'Etapa atual'}).count(),0);
    assert.equal(await p.locator('tbody tr').count(),2);
    assert.match(await p.locator('tbody').innerText(),/Pendente[\s\S]*Sem classificação/);
    assert.doesNotMatch(await p.locator('tbody').innerText(),/Realizada|Realizado/);
    for (const [status,nome] of [['TRIAGEM_PENDENTE','Antônio'],['CONSULTA_PENDENTE','João']]) {
      await p.locator('#status').selectOption(status);
      assert.equal(await p.locator('tbody tr').count(),1);
      assert.match(await p.locator('tbody').innerText(),new RegExp(nome));
    }
    await link('Pacientes').click();
    await p.waitForURL('**/pacientes.html');
    assert.equal(await link('Novo paciente').count() + await link('Novo atendimento').count(),0);
    assert.deepEqual(await p.locator('tbody tr').first().getByRole('link').allTextContents(),['Editar','Ver histórico']);
    await p.locator('tbody tr').first().getByRole('link',{name:'Ver histórico'}).click();
    await p.waitForURL('**/atendimentos.html?paciente=*');
    await link('Ver atendimento').first().click();
    await p.waitForURL('**/atendimento.html?id=3*');
    assert.match(await p.locator('.resumo-consulta').innerText(),/Registro legado/);
    await link('Registrar atendimento').click();
    await p.waitForURL('**/novo-atendimento.html');
    assert.equal(await p.locator('#menu [aria-current]').count(),0);
    assert.equal(await link('Voltar ao painel').count(),0);
    await link('Cadastrar novo paciente').click();
    await p.waitForURL('**/paciente-form.html?origem=chegada');
    await p.locator('#nome_completo').fill('Paciente do fluxo');
    await p.locator('#data_nascimento').fill('2000-02-01');
    await botao('Salvar e continuar').click();
    await p.waitForURL('**/novo-atendimento.html?paciente=5');
    await botao('Abrir atendimento').click();
    await p.waitForURL('**/atendimento.html?id=*&origem=abertura');
    const id = new URL(p.url()).searchParams.get('id');
    const linha = () => p.locator('tbody tr').filter({hasText:'Paciente do fluxo'});
    assert.equal(await p.getByRole('heading',{name:'Atendimento aberto',exact:true}).count(),1);
    assert.equal(await p.locator('.fluxo-paciente [aria-current="step"]').count(),0);
    assert.match(await p.locator('.fluxo-paciente .concluida').last().innerText(),/Abertura do atendimento/);
    assert.equal(await p.getByRole('heading',{name:'Triagem',exact:true}).count(),0);
    await link('Voltar ao painel').click();
    await p.waitForURL('**/painel.html');
    assert.equal(await linha().count(),1);
    assert.match(await linha().innerText(),/Triagem pendente/);
    await linha().getByRole('link',{name:'Visualizar',exact:true}).click();
    await p.waitForURL('**/atendimento.html?id=' + id + '&modo=visualizar');
    assert.equal(await p.getByRole('heading',{name:'Resumo do atendimento',exact:true}).count(),1);
    assert.equal(await p.locator('main a[href^="triagem.html"], main a[href^="consulta.html"]').count(),0);
    await link('Voltar ao painel').click();
    await p.waitForURL('**/painel.html');
    await linha().getByRole('link',{name:'Continuar',exact:true}).click();
    assert.equal(await link('Registrar triagem').count(),1);
    await abrir('atendimento.html?id=' + id + '&origem=abertura');
    await link('Iniciar triagem').click();
    await p.waitForURL('**/triagem.html?id=' + id);
    assert.match(await p.locator('[aria-current="step"]').innerText(),/Triagem/);
    await p.getByRole('radio',{name:'Azul',exact:true}).check();
    await botao('Salvar').click();
    await p.waitForURL('**/atendimento.html?id=' + id + '&origem=triagem');
    assert.equal(await p.getByRole('heading',{name:'Triagem registrada',exact:true}).count(),1);
    assert.equal(await p.locator('.fluxo-paciente [aria-current="step"]').count(),0);
    assert.match(await p.locator('.fluxo-paciente .concluida').last().innerText(),/Triagem/);
    await link('Voltar ao painel').click();
    await p.waitForURL('**/painel.html');
    assert.match(await linha().innerText(),/Consulta pendente/);
    await p.goBack();
    await link('Iniciar consulta').click();
    await p.waitForURL('**/consulta.html?id=' + id);
    assert.match(await p.locator('[aria-current="step"]').innerText(),/Consulta/);
    const medicamentos = p.getByRole('textbox',{name:'Medicamentos prescritos'});
    await medicamentos.fill('Texto de medicamentos\n<registro>');
    assert.equal(await p.getByRole('button',{name:'Adicionar medicamento'}).count(),0);
    await botao('Salvar').click();
    await p.waitForURL('**/atendimento.html?id=' + id);
    assert.match(await p.locator('.fluxo-paciente .concluida').last().innerText(),/Encerrado/);
    await link('Voltar ao painel').click();
    await p.waitForURL('**/painel.html');
    assert.equal(await linha().count(),0);
    await abrir('atendimentos.html?paciente=5');
    assert.match(await linha().innerText(),/Finalizado/);
    await p.locator('#status').selectOption('FINALIZADO');
    assert.equal(await linha().count(),1);
    await linha().getByRole('link').click();
    assert.match(await p.locator('.resumo-consulta').innerText(),/Texto de medicamentos\s+<registro>/);
    assert.equal(await p.locator('main a[href^="consulta.html"]').count(),0);
    await link('Painel').click();
    await p.waitForURL('**/painel.html');
    assert.equal(await linha().count(),0);
    await p.setViewportSize({width:375,height:812});
    assert.ok(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    assert.deepEqual(erros,[]);
    assert.deepEqual(rede,[]);
    console.log('Aprovado: navegação, cadastro pela recepção, dois status e filtros, migração local, triagem, consulta com texto, encerramento, histórico e layout móvel.');
  } finally { await navegador.close(); }
})().catch(e => {console.error(e); process.exitCode=1;});
